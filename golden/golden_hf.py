#!/usr/bin/env python3
"""Golden reference for GPT-2 (124M) FP32 inference using Hugging Face transformers.

Produces, in data/:
  prompt.txt / prompt_ids.i32          fixed prompt and its GPT-2 token IDs
  output_ids.i32 / output.txt          32 greedily decoded token IDs and decoded text
  acts/*.f32                           per-layer activations of the FIRST DECODE STEP
                                       (the token generated by prefill, at position T0)
  acts/l{ll}_k.f32, l{ll}_v.f32        K/V cache of every layer after that step, (T0+1, 768)
  decode0_logits.f32, decode0_top5.txt full logits (50257) and top-5 of that step
  long_prompt_ids.i32 / long_output_ids.i32
                                       992-token prompt + 32 greedy tokens (context 1024)
  manifest.txt                         name, dtype, shape of every file
It also checks that llm.c's gpt2_124M.bin holds the same weights as HF `gpt2`.

Inference only: torch.no_grad(), eval mode, FP32, batch 1, greedy (argmax), KV cache.
"""
import argparse
import os
import sys

import numpy as np
import torch
import transformers
from transformers import GPT2LMHeadModel, GPT2TokenizerFast

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROMPT = "The FPGA is"
N_NEW = 32
LONG_PROMPT_LEN = 992  # + 32 decoded tokens = 1024 = max context

# Fixed, self-written text used only to build a long deterministic prompt.
LONG_TEXT = (
    "Field-programmable gate arrays are reconfigurable chips that contain a large "
    "array of lookup tables, flip-flops, block memories and arithmetic slices. "
    "Engineers describe a circuit in a hardware description language or in C++ "
    "with high-level synthesis, and the tools map the design onto the fabric. "
    "Because the memory system of a modern data-center card offers hundreds of "
    "gigabytes per second, these devices are attractive for workloads that stream "
    "large tensors, such as the inference of transformer language models. "
)


class Manifest:
    def __init__(self, path):
        self.path = path
        self.lines = []

    def save(self, rel, arr):
        arr = np.ascontiguousarray(arr)
        full = os.path.join(ROOT, "data", rel)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        arr.tofile(full)
        self.lines.append(f"{rel} {arr.dtype} {' '.join(str(s) for s in arr.shape)}")

    def write(self):
        with open(self.path, "w") as f:
            f.write("# file dtype shape...  (raw little-endian, C order)\n")
            f.write("\n".join(self.lines) + "\n")


def check_llmc_weights(model, path):
    """Compare llm.c's checkpoint with HF weights (HF Conv1D stores (in, out) -> transpose)."""
    hdr = np.fromfile(path, dtype=np.int32, count=256)
    assert hdr[0] == 20240326 and hdr[1] == 3, "bad llm.c checkpoint header"
    maxT, V, L, NH, C, Vp = (int(x) for x in hdr[2:8])
    p = np.fromfile(path, dtype=np.float32, offset=256 * 4)
    sd = {k: v.detach().numpy() for k, v in model.state_dict().items()}
    off = 0

    def take(n):
        nonlocal off
        a = p[off:off + n]
        off += n
        return a

    max_diff = 0.0
    def cmp(a, b):
        nonlocal max_diff
        max_diff = max(max_diff, float(np.max(np.abs(a.reshape(-1) - b.reshape(-1)))))

    wte = take(Vp * C).reshape(Vp, C)
    cmp(wte[:V], sd["transformer.wte.weight"])
    pad_max = float(np.max(np.abs(wte[V:]))) if Vp > V else 0.0
    cmp(take(maxT * C), sd["transformer.wpe.weight"])
    h = "transformer.h.{}."
    per_layer = [
        ("ln_1.weight", C, False), ("ln_1.bias", C, False),
        ("attn.c_attn.weight", 3 * C * C, True), ("attn.c_attn.bias", 3 * C, False),
        ("attn.c_proj.weight", C * C, True), ("attn.c_proj.bias", C, False),
        ("ln_2.weight", C, False), ("ln_2.bias", C, False),
        ("mlp.c_fc.weight", 4 * C * C, True), ("mlp.c_fc.bias", 4 * C, False),
        ("mlp.c_proj.weight", 4 * C * C, True), ("mlp.c_proj.bias", C, False),
    ]
    # llm.c stores each tensor kind for all layers contiguously: (L, ...)
    for name, n, transpose in per_layer:
        blk = take(L * n)
        for l in range(L):
            ref = sd[h.format(l) + name]
            ref = ref.T if transpose else ref
            cmp(blk[l * n:(l + 1) * n], ref)
    cmp(take(C), sd["transformer.ln_f.weight"])
    cmp(take(C), sd["transformer.ln_f.bias"])
    assert off == p.size, f"checkpoint size mismatch {off} vs {p.size}"
    return max_diff, pad_max


def capture_hooks(model, store):
    """Forward hooks that record the activations of the LAST token of the current call."""
    hooks = []
    last = lambda t: t[0, -1].detach().clone().numpy()

    def out_hook(key):
        def f(mod, inp, out):
            o = out[0] if isinstance(out, tuple) else out
            store[key] = last(o)
        return f

    def in_hook(key):
        def f(mod, inp, out):
            store[key] = last(inp[0])
        return f

    tr = model.transformer
    hooks.append(tr.drop.register_forward_hook(out_hook("embed")))
    for l, blk in enumerate(tr.h):
        p = f"l{l:02d}_"
        hooks.append(blk.ln_1.register_forward_hook(out_hook(p + "ln1")))
        hooks.append(blk.attn.c_attn.register_forward_hook(out_hook(p + "qkv")))
        hooks.append(blk.attn.c_proj.register_forward_hook(in_hook(p + "atty")))
        hooks.append(blk.attn.c_proj.register_forward_hook(out_hook(p + "attproj")))
        hooks.append(blk.ln_2.register_forward_hook(in_hook(p + "res1")))
        hooks.append(blk.ln_2.register_forward_hook(out_hook(p + "ln2")))
        hooks.append(blk.mlp.c_fc.register_forward_hook(out_hook(p + "fch")))
        hooks.append(blk.mlp.act.register_forward_hook(out_hook(p + "fch_gelu")))
        hooks.append(blk.mlp.c_proj.register_forward_hook(out_hook(p + "fcproj")))
        hooks.append(blk.register_forward_hook(out_hook(p + "res2")))
    hooks.append(tr.ln_f.register_forward_hook(out_hook("lnf")))
    return hooks


@torch.no_grad()
def greedy(model, ids, n_new, hooks_store=None):
    """Prefill + token-by-token greedy decode with the HF KV cache."""
    out = model(torch.tensor([ids]), use_cache=True)
    past = out.past_key_values
    nxt = int(torch.argmax(out.logits[0, -1]))
    gen = [nxt]
    step0 = None
    for i in range(1, n_new):
        hooks = capture_hooks(model, hooks_store) if (hooks_store is not None and i == 1) else []
        out = model(torch.tensor([[nxt]]), past_key_values=past, use_cache=True)
        for h in hooks:
            h.remove()
        if i == 1:  # the cache is updated in place: snapshot it now
            kv = [kv_layer(out.past_key_values, l) for l in range(model.config.n_layer)]
            step0 = (out.logits[0, -1].clone(), kv)
        past = out.past_key_values
        nxt = int(torch.argmax(out.logits[0, -1]))
        gen.append(nxt)
    return gen, step0


def kv_layer(past, l):
    # transformers >= 4.5x: DynamicCache with .layers[l].keys / .values; older: tuple
    if hasattr(past, "layers"):
        k, v = past.layers[l].keys, past.layers[l].values
    elif hasattr(past, "key_cache"):
        k, v = past.key_cache[l], past.value_cache[l]
    else:
        k, v = past[l]
    # (1, NH, T, HS) -> (T, NH*HS), matching the qkv layout of llm.c / our C++ code
    to_tc = lambda t: t[0].permute(1, 0, 2).reshape(t.shape[2], -1).numpy().copy()
    return to_tc(k), to_tc(v)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--llmc-bin", default=os.path.join(ROOT, "models", "gpt2_124M.bin"))
    ap.add_argument("--threads", type=int, default=8)
    args = ap.parse_args()

    torch.manual_seed(0)
    torch.set_num_threads(args.threads)
    torch.backends.mkldnn.enabled = True
    tok = GPT2TokenizerFast.from_pretrained("gpt2")
    model = GPT2LMHeadModel.from_pretrained("gpt2", torch_dtype=torch.float32,
                                            attn_implementation="eager").eval()
    print(f"torch {torch.__version__}, transformers {transformers.__version__}")

    os.makedirs(os.path.join(ROOT, "data", "acts"), exist_ok=True)
    man = Manifest(os.path.join(ROOT, "data", "manifest.txt"))

    # 0) llm.c checkpoint == HF weights?
    if os.path.exists(args.llmc_bin):
        d, pad = check_llmc_weights(model, args.llmc_bin)
        print(f"[weights] llm.c gpt2_124M.bin vs HF gpt2: max |diff| = {d:.3e}, "
              f"max |padded wte row| = {pad:.3e}")
        with open(os.path.join(ROOT, "data", "weights_check.txt"), "w") as f:
            f.write(f"max_abs_diff {d:.6e}\npadded_wte_max_abs {pad:.6e}\n")
        if d != 0.0:
            print("WARNING: llm.c checkpoint differs from HF weights")
    else:
        print(f"[weights] {args.llmc_bin} not found; skipping checkpoint comparison")

    # 1) fixed short prompt, 32 greedy tokens, activations of first decode step
    ids = tok.encode(PROMPT)
    store = {}
    gen, (logits0, past0) = greedy(model, ids, N_NEW, store)
    # cross-check our loop against HF generate()
    ref = model.generate(torch.tensor([ids]), max_new_tokens=N_NEW, do_sample=False,
                         num_beams=1, pad_token_id=tok.eos_token_id)[0, len(ids):].tolist()
    assert ref == gen, f"manual greedy loop != generate(): {gen} vs {ref}"
    text = tok.decode(ids + gen)
    print(f"[prompt] {PROMPT!r} -> ids {ids}")
    print(f"[output] ids {gen}")
    print(f"[text] {text!r}")

    with open(os.path.join(ROOT, "data", "prompt.txt"), "w") as f:
        f.write(PROMPT)
    with open(os.path.join(ROOT, "data", "output.txt"), "w") as f:
        f.write(text)
    man.save("prompt_ids.i32", np.array(ids, dtype=np.int32))
    man.save("output_ids.i32", np.array(gen, dtype=np.int32))

    # first decode step: input token gen[0] at position len(ids)
    pos = len(ids)
    with open(os.path.join(ROOT, "data", "decode0_info.txt"), "w") as f:
        f.write(f"input_token {gen[0]}\nposition {pos}\noutput_token {gen[1]}\n")
    for k in sorted(store):
        man.save(f"acts/{k}.f32", store[k].astype(np.float32))
    for l in range(model.config.n_layer):
        k, v = past0[l]
        assert k.shape[0] == pos + 1
        man.save(f"acts/l{l:02d}_k.f32", k.astype(np.float32))
        man.save(f"acts/l{l:02d}_v.f32", v.astype(np.float32))
    lg = logits0.numpy().astype(np.float32)
    man.save("decode0_logits.f32", lg)
    top = np.argsort(-lg)[:5]
    with open(os.path.join(ROOT, "data", "decode0_top5.txt"), "w") as f:
        for t in top:
            f.write(f"{int(t)} {lg[t]:.6f} {tok.decode([int(t)])!r}\n")
    print("[decode0] top5:", [(int(t), float(lg[t])) for t in top])

    # 2) long prompt (context 1024) for long-context correctness
    long_ids = []
    while len(long_ids) < LONG_PROMPT_LEN:
        long_ids += tok.encode(LONG_TEXT)
    long_ids = long_ids[:LONG_PROMPT_LEN]
    long_gen, _ = greedy(model, long_ids, N_NEW)
    man.save("long_prompt_ids.i32", np.array(long_ids, dtype=np.int32))
    man.save("long_output_ids.i32", np.array(long_gen, dtype=np.int32))
    print(f"[long] {len(long_ids)} prompt tokens -> {long_gen}")

    man.write()
    print(f"wrote {len(man.lines)} files to data/")


if __name__ == "__main__":
    sys.exit(main())
