#!/usr/bin/env python3
"""Collect TAPA / Vitis HLS synthesis results of every kernel into
results/synthesis.csv and results/synthesis.md.

Sources (written by `make hls` in kernels/<name>/ into build/kernels/<name>/):
  work.out/report.yaml                 TAPA summary: total + per-task area,
                                       estimated clock period
  work.out/report/<task>_csynth.xml    per task: latency (cycles), est. clock
  work.out/report/<task>_Pipeline_*    per pipelined loop: achieved II, trip
                                       count, depth
Latency of runtime-sized loops uses the LOOP_TRIPCOUNT values in the kernel
sources (representative GPT-2 shapes, listed in TRIPCOUNT_NOTE below).
"""
import csv
import glob
import os
import xml.etree.ElementTree as ET

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KERNELS = ["gemv", "layernorm", "gelu", "residual", "attention", "lm_head"]
TRIPCOUNT_NOTE = {
    "gemv": "C=768, OC=3072 (MLP fc layer)",
    "layernorm": "1 row, C=768",
    "gelu": "3072 elements",
    "residual": "768 elements",
    "attention": "pos=1023 (full context), per layer",
    "lm_head": "V=50304 padded rows, C=768 (compile-time)",
}
AVAIL = {"LUT": 1303680, "FF": 2607360, "DSP": 9024, "BRAM_18K": 4032, "URAM": 960}
RES = ["LUT", "FF", "DSP", "BRAM_18K", "URAM"]


def txt(root, path, default=""):
    e = root.find(path)
    return e.text.strip() if e is not None and e.text else default


def task_xml(rep_dir, task):
    p = os.path.join(rep_dir, f"{task}_csynth.xml")
    if not os.path.exists(p):
        return None
    r = ET.parse(p).getroot()
    return dict(
        latency=txt(r, "PerformanceEstimates/SummaryOfOverallLatency/Worst-caseLatency"),
        clock=txt(r, "PerformanceEstimates/SummaryOfTimingAnalysis/EstimatedClockPeriod"),
    )


def loops(rep_dir, task):
    out = []
    for p in sorted(glob.glob(os.path.join(rep_dir, f"{task}_Pipeline_*_csynth.xml"))):
        r = ET.parse(p).getroot()
        name = os.path.basename(p)[len(task) + len("_Pipeline_"):-len("_csynth.xml")]
        first = lambda tag: next((e.text.strip() for e in r.iter(tag) if e.text), "")
        out.append(dict(
            loop=name,
            ii=first("PipelineII"),
            trip=first("TripCount"),
            depth=first("PipelineDepth"),
            latency=txt(r, "PerformanceEstimates/SummaryOfOverallLatency/Worst-caseLatency"),
        ))
    # loops pipelined inside the task body (not outlined) appear in the task xml
    p = os.path.join(rep_dir, f"{task}_csynth.xml")
    if os.path.exists(p):
        r = ET.parse(p).getroot()
        for lp in r.iter():
            if lp.tag.startswith("VITIS_LOOP") or lp.tag.startswith("Loop"):
                ii = txt(lp, "PipelineII")
                if ii:
                    out.append(dict(loop=lp.tag, ii=ii, trip=txt(lp, "TripCount"),
                                    depth=txt(lp, "PipelineDepth"),
                                    latency=txt(lp, "Latency")))
    return out


def main():
    rows, md = [], []
    md.append("# HLS synthesis results\n")
    md.append("Generated by `analysis/collect_synth.py` from TAPA/Vitis HLS 2024.2 reports "
              "(part xcu55c-fsvh2892-2L-e, target clock 3.33 ns = 300 MHz). HLS estimates only "
              "(no place-and-route). Kernel latency estimate = slowest task, because TAPA tasks "
              "run concurrently (dataflow).\n")
    md.append("| kernel | trip-count assumption | est. latency (cycles) | est. latency @300 MHz | "
              "worst pipelined-loop II | est. clock (ns) | est. Fmax (MHz) | LUT | FF | DSP | "
              "BRAM_18K | URAM |")
    md.append("|---" * 12 + "|")
    loop_md = ["\n## Pipelined loops (achieved II)\n",
               "| kernel | task | loop | II | trip count | depth |", "|---|---|---|---|---|---|"]
    for k in KERNELS:
        wd = os.path.join(ROOT, "build", "kernels", k, "work.out")
        ry = os.path.join(wd, "report.yaml")
        if not os.path.exists(ry):
            md.append(f"| {k} | not synthesized | | | | | | | | | | |")
            continue
        y = yaml.safe_load(open(ry))
        clk = float(y["performance"]["clock_period"])
        tot = y["area"]["total"]
        rep_dir = os.path.join(wd, "report")
        lat_max, ii_max = 0, 1
        for task, info in sorted(y["area"]["breakdown"].items()):
            tx = task_xml(rep_dir, task) or {}
            a = info["area"]["total"]
            lat = tx.get("latency", "")
            if lat.isdigit():
                lat_max = max(lat_max, int(lat))
            rows.append(dict(kernel=k, level="task", name=task, count=info["count"],
                             latency_cycles=lat, ii="", trip_count="",
                             est_clock_ns=tx.get("clock", ""),
                             **{r: a.get(r, 0) for r in RES}))
            for lp in loops(rep_dir, task):
                rows.append(dict(kernel=k, level="loop", name=f"{task}/{lp['loop']}", count="",
                                 latency_cycles=lp["latency"], ii=lp["ii"],
                                 trip_count=lp["trip"], est_clock_ns=""))
                loop_md.append(f"| {k} | {task} | {lp['loop']} | {lp['ii']} | {lp['trip']} | "
                               f"{lp['depth']} |")
                if lp["ii"].isdigit():
                    ii_max = max(ii_max, int(lp["ii"]))
        rows.append(dict(kernel=k, level="kernel", name=y["name"], count=1,
                         latency_cycles=lat_max, ii=ii_max, trip_count=TRIPCOUNT_NOTE[k],
                         est_clock_ns=clk, **{r: tot.get(r, 0) for r in RES}))
        util = lambda r: f"{tot.get(r, 0)} ({100 * tot.get(r, 0) / AVAIL[r]:.1f}%)"
        md.append(f"| {k} | {TRIPCOUNT_NOTE[k]} | {lat_max} | {lat_max * 3.33e-3:.1f} us | "
                  f"{ii_max} | {clk:.3f} | {1000 / clk:.0f} | " +
                  " | ".join(util(r) for r in RES) + " |")
    md.append("\nUtilization in parentheses is relative to the full XCU55C "
              f"({', '.join(f'{r} {v}' for r, v in AVAIL.items())}); the shell/platform region "
              "is not subtracted.\n")
    md += loop_md
    cols = ["kernel", "level", "name", "count", "latency_cycles", "ii", "trip_count",
            "est_clock_ns"] + RES
    with open(os.path.join(ROOT, "results", "synthesis.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    with open(os.path.join(ROOT, "results", "synthesis.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print("\n".join(md[:4 + len(KERNELS) + 2]))


if __name__ == "__main__":
    main()
